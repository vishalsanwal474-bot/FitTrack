import { toPng } from 'html-to-image';
import { jsPDF } from 'jspdf';

function downloadDataUrl(dataUrl, filename) {
  const link = document.createElement('a');
  link.download = filename;
  link.href = dataUrl;
  link.click();
}

export async function exportCardPng(node, filename = 'fittrack-progress.png') {
  if (!node) throw new Error('Card not ready');
  const dataUrl = await toPng(node, {
    cacheBust: true,
    pixelRatio: 2,
    backgroundColor: '#1a2332',
  });
  downloadDataUrl(dataUrl, filename);
  return dataUrl;
}

export async function exportReportPdf(report, filename = 'fittrack-report.pdf') {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const margin = 48;
  let y = margin;
  const pageWidth = doc.internal.pageSize.getWidth();
  const maxWidth = pageWidth - margin * 2;

  const line = (text, size = 11, style = 'normal', color = [15, 20, 25]) => {
    doc.setFont('helvetica', style);
    doc.setFontSize(size);
    doc.setTextColor(...color);
    const lines = doc.splitTextToSize(String(text), maxWidth);
    doc.text(lines, margin, y);
    y += lines.length * (size + 4) + 4;
    if (y > doc.internal.pageSize.getHeight() - margin) {
      doc.addPage();
      y = margin;
    }
  };

  const stats = report.stats || {};

  line('FitTrack Progress Report', 20, 'bold', [26, 35, 50]);
  line(report.userName || 'Athlete', 12, 'normal', [61, 74, 92]);
  line(report.label || '', 12, 'bold', [155, 196, 26]);
  y += 8;

  line('Summary', 14, 'bold');
  line(`Workouts: ${stats.workouts ?? 0}`);
  line(`Volume: ${stats.volume ?? 0} kg`);
  line(`Calories burned: ~${stats.calories ?? 0} kcal`);
  line(`Duration: ${stats.duration ?? 0} min`);
  line(`Sets: ${stats.sets ?? 0}`);
  line(`Current streak: ${stats.streak ?? 0} days`);
  line(`New PRs this period: ${stats.newPRs ?? 0}`);
  if (stats.currentWeight != null) line(`Current weight: ${stats.currentWeight} kg`);
  y += 8;

  if (report.muscles?.length) {
    line('Muscle focus', 14, 'bold');
    report.muscles.forEach((m) => line(`${m.name}: ${m.value}`));
    y += 8;
  }

  if (report.topPRs?.length) {
    line('Personal records', 14, 'bold');
    report.topPRs.forEach((pr) => {
      line(
        `${pr.exerciseName} — ${pr.maxWeight} kg × ${pr.maxWeightReps} (vol ${Math.round(pr.maxVolume || 0)} kg)`
      );
    });
    y += 8;
  }

  if (report.recentWorkouts?.length) {
    line('Recent workouts', 14, 'bold');
    report.recentWorkouts.forEach((w) => {
      const date = new Date(w.date).toLocaleDateString();
      const parts = (w.bodyParts || []).join(' + ') || 'General';
      line(`${date} · ${parts} · ${w.duration} min · ${w.volume} kg · ~${w.caloriesBurned || 0} kcal`);
    });
  }

  y += 16;
  line('Generated by FitTrack', 9, 'normal', [107, 122, 143]);

  doc.save(filename);
}
